// Description: Generate a small, repository-local context map from checked authoritative sources.
import { readFileSync, writeFileSync, existsSync, readdirSync, mkdirSync } from 'node:fs';
import { dirname, join, posix, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { safePath } from './distribution.mjs';

export function renderAIContext(root = process.cwd()) {
const at = path => join(root, path);
const manifest=JSON.parse(readFileSync(at('framework.manifest.json'),'utf8'));
const target = safePath(manifest.contextOutput ?? 'docs/04-ai/context.gen.md');
// Keep the existing repository's generated bytes stable; application templates opt into a new output path.
const link = path => manifest.contextOutput ? posix.relative(posix.dirname(target), path) : `../../${path}`;
const spec=JSON.parse(readFileSync(at(manifest.contract),'utf8'));
const paths=[...manifest.readFirst,...Object.values(manifest.sources),...Object.values(manifest.profiles).map(profile=>profile.entry)];
for(const path of paths)if(!existsSync(at(path)))throw new Error(`Framework manifest references missing path: ${path}`);
const skills=readdirSync(at('.agents/skills'),{withFileTypes:true}).filter(item=>item.isDirectory()).map(item=>item.name).sort();
if(JSON.stringify(skills)!==JSON.stringify([...manifest.skills].sort()))throw new Error('Manifest skill catalogue differs from .agents/skills');
const methods=new Set(['get','post','put','patch','delete','head','options']);
const operations=Object.values(spec.paths).flatMap(path=>Object.entries(path).filter(([method])=>methods.has(method))).length;
let content='<!-- Code generated by scripts/ai-context.mjs; DO NOT EDIT. -->\n<!-- Author: yunnuo <ymz@ebox.vip> -->\n# AI 开发上下文入口\n\n此文件只提供导航；行为与完成状态以链接的源码、当前需求和验收为准。用户本次指令优先。\n\n';
content+='先读：'+manifest.readFirst.map(path=>`[${path}](${link(path)})`).join(' → ')+'。\n\n';
content+='| Profile | 组合根 | 身份 | 存储 |\n| --- | --- | --- | --- |\n';
for(const [name,profile] of Object.entries(manifest.profiles))content+=`| ${name} | [${profile.entry}](${link(profile.entry)}) | ${profile.identity?'平台会话/RBAC':'不装配平台身份'} | ${profile.storage} |\n`;
content+='\n| 唯一来源 | 位置 |\n| --- | --- |\n';
for(const [name,path] of Object.entries(manifest.sources))content+=`| ${name} | [${path}](${link(path)}) |\n`;
content+=`\nOpenAPI 当前包含 ${operations} 个 operation、${Object.keys(spec.components.schemas).length} 个 schema。Go/TS 模型、调用描述与离线文档从同一源生成。不要手改生成文件。\n\n`;
content+='| 任务 Skill | 用途 |\n| --- | --- |\n';
for(const skill of skills){
 const path=`.agents/skills/${skill}/SKILL.md`;const text=readFileSync(at(path),'utf8');
 if(!text.startsWith('---\n')||!text.includes(`\nname: ${skill}\n`))throw new Error(`Invalid skill discovery metadata: ${path}`);
 const description=text.match(/^description: (.+)$/m)?.[1];if(!description)throw new Error(`Missing description: ${path}`);
 content+=`| [${skill}](${link(path)}) | ${description.replaceAll('|','\\|')} |\n`;
}
content+='\n常用命令：\n\n';for(const [purpose,command] of Object.entries(manifest.commands))content+=`- ${purpose}：\`${command}\`\n`;
const taskLink = manifest.contextOutput ? link(safePath(manifest.taskTemplate ?? 'docs/04-ai/task-template.md')) : 'task-template.md';
content+=`\n不保存凭据到上下文或验收记录。任务记录使用 [任务模板](${taskLink})，交付记录须区分实测、未测与未来目标。\n`;
return { target, content };
}
export function writeAIContext(root = process.cwd(), check = false) {
  const {target, content} = renderAIContext(root);
  const path = join(root, target);
  if (check) { if (readFileSync(path, 'utf8') !== content) throw Error('AI context is stale; run pnpm ai:context'); }
  else { mkdirSync(dirname(path), {recursive: true}); writeFileSync(path, content); }
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) writeAIContext(process.cwd(), process.argv.includes('--check'));
