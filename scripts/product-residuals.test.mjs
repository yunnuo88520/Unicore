function project(){
 const root=mkdtempSync(join(tmpdir(),'unicore-residual-'));
 delete files['product.identity.json.dup'];
 for(const [p,text] of Object.entries(files)){mkdirSync(dirname(join(root,p)),{recursive:true});writeFileSync(join(root,p),text);}
 return root;
}

test('residue scan passes a clean derived tree and skips framework checkouts',()=>{
 const root=project();
 try{
  assert.deepEqual(scanResiduals(root),[]);
  assert.throws(()=>scanResiduals(root.replace(/\/$/,'')+'-missing'),/ENOENT/);
 }finally{rmSync(root,{recursive:true,force:true});}
});

test('residue scan reports framework identity in product surfaces and deployment file names',()=>{
 const root=project();
 try{
  writeFileSync(join(root,'apps/web/index.html'),'<!doctype html><html><head><title>Unicore · 工作空间</title></head></html>\n');
  writeFileSync(join(root,'deploy/tar/unicore.service'),'[Service]\n');
  const violations=scanResiduals(root);
  assert.ok(violations.some(entry=>entry.startsWith('apps/web/index.html:1')),JSON.stringify(violations));
  assert.ok(violations.some(entry=>entry.includes('deploy/tar/unicore.service: deployment file name')),JSON.stringify(violations));
  // attribution and mechanism lines stay whitelisted
  writeFileSync(join(root,'apps/web/index.html'),'<!doctype html><html><head><meta name="author" content="Author: yunnuo"><title>@unicore/web x-unicore UNICORE_PLATFORM_SIGNING unicore_session unicore.db</title></head></html>\n');
  assert.deepEqual(scanResiduals(root).filter(entry=>entry.startsWith('apps/web/index.html')),[]);
 }finally{rmSync(root,{recursive:true,force:true});}
});

test('residue scan requires provenance and identity',()=>{
 const root=project();
 try{
  writeFileSync(join(root,'project.provenance.json'),'{"upstream":"https://github.com/yunnuo88520/Unicore"}');
  assert.throws(()=>scanResiduals(root),/must name the upstream framework/);
 }finally{rmSync(root,{recursive:true,force:true});}
});
