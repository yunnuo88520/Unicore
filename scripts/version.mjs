// Description: VERSION is the only handwritten application version; synchronize its projections.
import { readFileSync, writeFileSync } from 'node:fs';

const check = process.argv.includes('--check');
const next = process.argv[process.argv.indexOf('--release') + 1];
const releasing = process.argv.includes('--release');
const current = readFileSync('VERSION', 'utf8').trim();
const valid = value => /^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/.test(value ?? '');
if (!valid(current) || (releasing && !valid(next))) throw new Error('Use a numeric SemVer (major.minor.patch)');
if (releasing) {
  const a = next.split('.').map(BigInt), b = current.split('.').map(BigInt);
  const diff = a.findIndex((part, i) => part !== b[i]);
  if (diff < 0 || a[diff] < b[diff]) throw new Error('New version must be greater than VERSION');
  const log = readFileSync('CHANGELOG.md', 'utf8');
  if (log.includes(`## ${next} `)) throw new Error('Changelog version already exists');
  const match = log.match(/## Unreleased\n([\s\S]*?)(?=\n## |$)/);
  if (!match || !match[1].trim()) throw new Error('Add release notes under ## Unreleased first');
  const date = new Date().toISOString().slice(0, 10);
  writeFileSync('CHANGELOG.md', log.replace(match[0], `## Unreleased\n\n## ${next} — ${date}\n${match[1]}`));
  writeFileSync('VERSION', `${next}\n`);
}
const version = releasing ? next : current;
function output(path, content) {
  if (check) { if (readFileSync(path, 'utf8') !== content) throw new Error(`${path} version is stale; run pnpm version:sync`); }
  else writeFileSync(path, content);
}
for (const path of ['package.json', 'apps/web/package.json', 'apps/desktop/package.json', 'packages/contracts/package.json', 'packages/sdk/package.json', 'packages/web-ui/package.json', 'packages/contracts/openapi.json', 'cmd/desktop/wails.json']) {
  const data = JSON.parse(readFileSync(path, 'utf8'));
  if (path.endsWith('openapi.json')) data.info.version = version;
  else if (path.endsWith('wails.json')) data.info.productVersion = version;
  else data.version = version;
  output(path, `${JSON.stringify(data, null, 2)}\n`);
}
output('internal/buildinfo/version.gen.go', `// Code generated by scripts/version.mjs; DO NOT EDIT.\n// Author: yunnuo <ymz@ebox.vip>\n\npackage buildinfo\n\nconst sourceVersion = "${version}"\n`);
console.log(`${check ? 'PASS' : 'Synchronized'} application version ${version}`);
