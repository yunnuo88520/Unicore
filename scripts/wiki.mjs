// Description: Render Wiki pages from repository Markdown; publish only on an explicit command from clean, pushed main.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, isAbsolute, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const defaultRepository = 'yunnuo88520/Unicore';
export function repositoryName(value) {
  if (!/^[A-Za-z0-9][A-Za-z0-9-]*\/[A-Za-z0-9][A-Za-z0-9_.-]*$/.test(value) || value.endsWith('.git')) throw Error('Use a GitHub owner/repo for UNICORE_WIKI_REPOSITORY');
  return value;
}
export function wikiLink(target, { source, repository, pages, image = false, sourceRoot = root }) {
  if (!target || target.startsWith('#') || /^[a-z][a-z0-9+.-]*:/i.test(target)) return target;
  if (target.startsWith('//') || target.startsWith('/')) throw Error(`${source}: use repository-relative documentation links`);
  const hashAt = target.indexOf('#'), path = hashAt < 0 ? target : target.slice(0, hashAt), hash = hashAt < 0 ? '' : target.slice(hashAt);
  const full = resolve(sourceRoot, dirname(source), decodeURIComponent(path));
  const local = relative(sourceRoot, full);
  if (isAbsolute(local) || local === '..' || local.startsWith('..' + sep) || !existsSync(full)) throw Error(`${source}: invalid Wiki source link ${target}`);
  const normalized = local.split(sep).join('/');
  const mapped = pages.get(normalized);
  if (!image && mapped) return `https://github.com/${repository}/wiki/${mapped}${hash}`;
  const encoded = normalized.split('/').map(encodeURIComponent).join('/');
  if (image) return `https://raw.githubusercontent.com/${repository}/main/${encoded}${hash}`;
  return `https://github.com/${repository}/${statSync(full).isDirectory() ? 'tree' : 'blob'}/main/${encoded}${hash}`;
}
export function renderMarkdown(text, options) {
  // Leave code examples intact, including Markdown examples inside fenced blocks.
  return text.split(/(^```[^\n]*\n[\s\S]*?^```[^\n]*$)/gm).map((part, index) => index % 2 ? part : part.replace(/(!?)\[([^\]]*)\]\(([^)]+)\)/g, (_, mark, label, target) => {
    const match = target.match(/^(<[^>]*>|\S+)(\s+"[^"]*")?$/);
    if (!match) throw Error(`${options.source}: unsupported Markdown link ${target}`);
    const bare = match[1].replace(/^<|>$/g, '');
    return `${mark}[${label}](${wikiLink(bare, { ...options, image: mark === '!' })}${match[2] ?? ''})`;
  })).join('');
}
export function generateWiki({ repository = defaultRepository, output = join(root, 'build/wiki'), check = false } = {}) {
  repositoryName(repository);
  const config = JSON.parse(readFileSync(join(root, 'docs/wiki/pages.json'), 'utf8'));
  const slugs = new Set(), pages = new Map();
  for (const page of config.pages) {
    if (!/^[A-Za-z0-9]+(?:-[A-Za-z0-9]+)*$/.test(page.slug) || slugs.has(page.slug) || pages.has(page.source)) throw Error('Wiki page names and sources must be unique');
    if (!page.title || !page.source.endsWith('.md') || !existsSync(join(root, page.source))) throw Error(`Missing Wiki source: ${page.source}`);
    slugs.add(page.slug); pages.set(page.source, page.slug);
  }
  if (!slugs.has('Home')) throw Error('Wiki Home is required');
  const base = `https://github.com/${repository}`;
  const rendered = new Map();
  for (const page of config.pages) {
    const text = readFileSync(join(root, page.source), 'utf8');
    const content = renderMarkdown(text, { source: page.source, repository, pages });
    const sourceURL = `${base}/blob/main/${page.source}`;
    rendered.set(page.slug + '.md', `<!-- Generated by scripts/wiki.mjs; edit the source document. -->\n<!-- Author: yunnuo <ymz@ebox.vip> -->\n> 本页从 [仓库源码](${sourceURL}) 生成，请在源码提交修改。\n\n${content}`);
  }
  rendered.set('_Sidebar.md', `<!-- Author: yunnuo <ymz@ebox.vip> -->\n**Unicore 文档**\n\n${config.pages.map(page => `- [${page.title}](${base}/wiki/${page.slug})`).join('\n')}\n\n[源码](${base}) · [反馈](${base}/issues)\n`);
  const version = readFileSync(join(root, 'VERSION'), 'utf8').trim();
  rendered.set('_Footer.md', `<!-- Author: yunnuo <ymz@ebox.vip> -->\nUnicore ${version} · 开发预览 · [MIT](${base}/blob/main/LICENSE) · [文档源码](${base}/tree/main/docs) · [同步方式](${base}/wiki/Wiki-Maintenance)\n`);
  if (!check) {
    mkdirSync(output, { recursive: true });
    for (const [file, text] of rendered) writeFileSync(join(output, file), text);
  }
  return rendered;
}
function git(...args) { return execFileSync('git', args, { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim(); }
function publish(repository) {
  if (git('branch', '--show-current') !== 'main') throw Error('Publish Wiki from main only');
  if (git('status', '--porcelain')) throw Error('Commit or remove local changes before publishing Wiki');
  const remote = git('remote', 'get-url', 'origin');
  if (![ `https://github.com/${repository}.git`, `https://github.com/${repository}`, `git@github.com:${repository}.git` ].includes(remote)) throw Error('origin does not match UNICORE_WIKI_REPOSITORY');
  const revision = git('rev-parse', 'HEAD');
  const remoteHead = git('ls-remote', 'origin', 'refs/heads/main').split(/\s+/)[0];
  if (remoteHead !== revision) throw Error('Push main before publishing its Wiki');
  const rendered = generateWiki({ repository });
  const temporary = mkdtempSync(join(tmpdir(), 'unicore-wiki-'));
  try {
    const checkout = join(temporary, 'wiki');
    try { git('clone', '--depth=1', `https://github.com/${repository}.wiki.git`, checkout); }
    catch { throw Error('Wiki clone failed: initialize Home in GitHub Wiki first, then check connectivity and existing Git access'); }
    for (const [file, text] of rendered) writeFileSync(join(checkout, file), text);
    git('-C', checkout, 'add', '--', ...rendered.keys());
    if (!git('-C', checkout, 'diff', '--cached', '--name-only')) { console.log('Wiki already matches the source'); return; }
    git('-C', checkout, 'commit', '-m', `docs: sync Unicore Wiki from ${revision.slice(0, 7)}`);
    git('-C', checkout, 'push', 'origin', 'HEAD');
    console.log(`Published ${rendered.size - 2} Wiki pages from ${revision.slice(0, 7)} to https://github.com/${repository}/wiki`);
  } finally { rmSync(temporary, { recursive: true, force: true }); }
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try {
    const args = process.argv.slice(2);
    if (args.some(arg => !['--check', '--publish'].includes(arg)) || args.length > 1) throw Error('Use wiki.mjs [--check|--publish]');
    const repository = repositoryName(process.env.UNICORE_WIKI_REPOSITORY ?? defaultRepository);
    if (args[0] === '--publish') publish(repository);
    else console.log(`PASS ${generateWiki({ repository, check: args[0] === '--check' }).size - 2} Wiki pages ${args[0] === '--check' ? 'validated' : 'generated in build/wiki'}`);
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
