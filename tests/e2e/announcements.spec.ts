import { mkdir } from 'node:fs/promises';
import { test, expect, installStandalone } from './fixtures';

test('announcement bell: management, popup retry, pagination, receipts, audiences and restart', async ({ page, browser, instance }, info) => {
  test.setTimeout(120000);
  expect((await page.request.post(`${instance.url}/api/v1/install/complete`, { headers: { 'X-Bootstrap-Token': instance.token }, data: { profile: 'web-platform', database: { driver: 'sqlite', dsn: '' }, site_name: 'Unicore', base_url: instance.url, admin_username: 'admin', admin_email: 'admin@example.test', admin_password: 'test-password-strong' } })).status()).toBe(200);
  const meta = (await (await page.request.get(`${instance.url}/api/v1/admin/bootstrap`)).json()).data;
  const headers = { 'X-CSRF-Token': meta.csrf_token };
  const member = (await (await page.request.post(`${instance.url}/api/v1/admin/users`, { headers, data: { username: 'member', email: 'member@example.test', password: 'test-password-strong', role: 'user' } })).json()).data;
  await page.request.patch(`${instance.url}/api/v1/admin/settings`, { headers, data: { changes: [{ key: 'security.login_captcha', value: 'false' }] } });
  const base = { title: '平台消息', content: '欢迎 **Unicore** [帮助](https://example.test/help)', format: 'markdown', type: 'info', note: 'private-note', status: 'published', publish_at: Math.floor(Date.now() / 1000), ends_at: 0, notify_mode: 'silent', audience: 'all', recipient_ids: [] };
  for (let i = 0; i < 12; i++) expect((await page.request.post(`${instance.url}/api/v1/admin/announcements`, { headers, data: { ...base, title: `静默消息 ${i}` } })).status()).toBe(200);
  const popup = (await (await page.request.post(`${instance.url}/api/v1/admin/announcements`, { headers, data: { ...base, title: '重要通知', notify_mode: 'popup', audience: 'selected', recipient_ids: [member.id] } })).json()).data;
  const next = (await (await page.request.post(`${instance.url}/api/v1/admin/announcements`, { headers, data: { ...base, title: '后续通知', notify_mode: 'popup', publish_at: base.publish_at - 1 } })).json()).data;
  const hidden = (await (await page.request.post(`${instance.url}/api/v1/admin/announcements`, { headers, data: { ...base, title: '未到期发布', publish_at: base.publish_at + 3600 } })).json()).data;
  const directory = `build/acceptance/announcements/${info.project.name}`;
  await mkdir(directory, { recursive: true });
  await page.goto(`${instance.url}/admin/announcements`);
  await expect(page.getByRole('heading', { name: '公告列表', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: '平台公告', exact: true }).filter({ has: page.locator('svg.lucide-bell') })).toHaveCount(0);
  // New notices default to draft, and the editor previews unsaved content.
  await page.getByRole('button', { name: '新增公告', exact: true }).click();
  const editor = page.getByRole('dialog', { name: '新增公告', exact: true });
  await editor.getByLabel('公告标题', { exact: true }).fill('编辑器草稿');
  await editor.getByLabel('公告内容', { exact: true }).fill('## 测试预览');
  await expect(editor.getByRole('combobox', { name: '发布状态', exact: true })).toHaveValue('draft');
  await editor.getByRole('combobox', { name: '接收范围', exact: true }).selectOption('selected');
  await expect(editor.getByText('member · member@example.test', { exact: true })).toBeVisible();
  await editor.getByRole('checkbox').check();
  await editor.getByRole('button', { name: '预览', exact: true }).click();
  await expect(editor.locator('.announcement-preview h2')).toHaveText('测试预览');
  await editor.getByRole('button', { name: '保存', exact: true }).click();
  await expect(page.getByText('公告已保存', { exact: true })).toBeVisible();
  const context = await browser.newContext({ viewport: page.viewportSize()! });
  try {
    expect((await context.request.post(`${instance.url}/api/v1/auth/login`, { data: { username: 'member', password: 'test-password-strong', captcha_id: '', captcha_answer: '' } })).status()).toBe(200);
    const user = await context.newPage();
    const bootstrap = (await (await context.request.get(`${instance.url}/api/v1/bootstrap`)).json()).data;
    const userHeaders = { 'X-CSRF-Token': bootstrap.csrf_token };
    await user.route('**/announcements/*/read', route => route.fulfill({ status: 500, contentType: 'application/json', body: JSON.stringify({ code: 'INTERNAL_ERROR', message: 'temporary failure', request_id: 'test' }) }));
    await user.goto(instance.url);
    await expect(user.locator('.announcement-card')).toHaveCount(0);
    const notice = user.getByRole('dialog', { name: '重要通知', exact: true });
    await expect(notice).toBeVisible();
    await user.keyboard.press('Escape');
    await expect(notice).toBeVisible();
    await notice.getByRole('button', { name: '标为已读', exact: true }).click();
    await expect(notice.getByRole('alert')).toHaveText('已读状态保存失败，请重试。');
    await user.unroute('**/announcements/*/read');
    await notice.getByRole('button', { name: '标为已读', exact: true }).click();
    await expect(notice).toHaveCount(0);
    const nextNotice = user.getByRole('dialog', { name: '后续通知', exact: true });
    await expect(nextNotice).toBeVisible();
    await nextNotice.getByRole('button', { name: '标为已读', exact: true }).click();
    await expect(nextNotice).toHaveCount(0);
    await expect(nextNotice).toHaveCount(0);
    const firstRead = (await (await context.request.get(`${instance.url}/api/v1/announcements/${popup.id}`)).json()).data.read_at;
    expect(firstRead).toBeGreaterThan(0);
    expect((await context.request.post(`${instance.url}/api/v1/announcements/${popup.id}/read`, { headers: userHeaders })).status()).toBe(200);
    expect((await (await context.request.get(`${instance.url}/api/v1/announcements/${popup.id}`)).json()).data.read_at).toBe(firstRead);
    expect((await context.request.get(`${instance.url}/api/v1/announcements/${hidden.id}`)).status()).toBe(404);
    const bell = user.getByRole('button', { name: '平台公告', exact: true });
    await expect(bell).toBeVisible();
    // The bell combines 12 unread announcements and the independently unread personal delivery.
    await expect(bell).toContainText('13');
    await bell.click();
    const inbox = user.getByRole('dialog', { name: '平台公告', exact: true });
    await expect(inbox.getByText('12 条未读公告', { exact: true })).toBeVisible();
    await inbox.getByRole('button', { name: '下一页', exact: true }).click();
    await expect(inbox.getByText('2 / 2', { exact: true })).toBeVisible();
    await inbox.getByRole('button', { name: '全部标为已读', exact: true }).click();
    await expect(inbox.getByText('0 条未读公告', { exact: true })).toBeVisible();
    expect((await (await context.request.get(`${instance.url}/api/v1/announcements?page=1&page_size=1`)).json()).data.unread_count).toBe(0);
    await user.keyboard.press('Escape');
    await expect(bell).toBeFocused();
    await user.getByRole('button', { name: '切换语言', exact: true }).click();
    await user.getByRole('menuitemradio', { name: 'English', exact: true }).click();
    await user.getByRole('button', { name: 'Appearance', exact: true }).click();
    await user.getByRole('dialog', { name: 'Appearance', exact: true }).locator('.preference-theme').getByRole('button', { name: 'Dark', exact: true }).click();
    await user.keyboard.press('Escape');
    await user.getByRole('button', { name: 'Announcements', exact: true }).click();
    const english = user.getByRole('dialog', { name: 'Announcements', exact: true });
    await expect(english.getByText('0 unread announcements', { exact: true })).toBeVisible();
    await user.screenshot({ path: `${directory}/bell-inbox-en-dark.png`, animations: 'disabled' });
    await english.getByRole('button').filter({ hasText: '静默消息' }).first().click();
    await expect(user.getByRole('link', { name: '帮助', exact: true })).toHaveAttribute('href', 'https://example.test/help');
    await expect(user.getByRole('dialog').last()).not.toContainText('private-note');
    expect(await user.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await user.screenshot({ path: `${directory}/bell-detail-en-dark.png`, animations: 'disabled' });
    await page.reload();
    await page.getByRole('button', { name: '阅读情况', exact: true }).first().click();
    await expect(page.getByRole('dialog', { name: '阅读情况', exact: true }).getByText('member', { exact: true })).toBeVisible();
    await page.keyboard.press('Escape');
    await page.locator('#announcements-enabled').uncheck();
    await user.reload();
    await user.getByRole('button', { name: 'Announcements', exact: true }).click();
    await expect(user.getByText('No announcements yet', { exact: true })).toBeVisible();
    expect((await context.request.post(`${instance.url}/api/v1/announcements/${popup.id}/read`, { headers: userHeaders })).status()).toBe(404);
    await instance.restart();
    await page.reload();
    await expect(page.locator('#announcements-enabled')).not.toBeChecked();
    await page.locator('#announcements-enabled').check();
    expect((await (await context.request.get(`${instance.url}/api/v1/announcements/${popup.id}`)).json()).data.read_at).toBe(firstRead);
  } finally { await context.close(); }
});

test('local workspace never requests announcement APIs', async ({ page, instance }) => {
  await installStandalone(instance);
  const requests: string[] = [];
  page.on('request', request => { if (request.url().includes('/announcements')) requests.push(request.url()); });
  await page.goto(instance.url);
  await expect(page.getByRole('heading', { name: '工作台概览' })).toBeVisible();
  await expect(page.getByRole('button', { name: '平台公告', exact: true })).toHaveCount(0);
  expect(requests).toEqual([]);
});
